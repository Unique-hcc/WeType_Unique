#!/usr/bin/env python3
"""从模块仓库的 Release 列表里挑出「模块本体」APK。

坑（2026-11-18 踩到）：本仓库同时存在两类 Release
  1) 你手发的模块版本，如 WeType_Unique_1.29.0（含 6MB 模块 + 226MB 已内置整包）
  2) 本流水线自动发的成品，如 WeType_4.0.1.59201_V1.29.0（只有 226MB 整包）
用 /releases/latest 会拿到 (2)，把 226MB 整包当模块喂给 LSPatch，结果
"module.apk does not exist or is not a valid apk" 然后静默跳过内置。

所以这里改成：拉 Release 列表 -> 剔除流水线自己发的 -> 取最新的一个。
剔除有两种判据（任一命中即剔除）：
  a. body 里含 auto-generated by wetype-patch 标记（发布时写入）
  b. tag 形如 WeType_<数字...>_V<数字...>（本流水线的命名规则）

环境变量：
  MODULE_REPO     例：Unique-hcc/WeType_Unique
  MODULE_ASSET    可选，资产名精确/包含匹配
  MAX_MODULE_MB   可选，模块体积上限，默认 50；超限直接报错（多半是挑错了）
  GH_TOKEN        GitHub token，避免 API 限流

输出：tag / version / asset / url / size
"""
import json
import os
import re
import sys
import urllib.request

API = "https://api.github.com"
AUTO_MARK = "auto-generated by wetype-patch"
AUTO_TAG = re.compile(r"^WeType_\d[\w.]*_V\d")


def get(url: str):
    req = urllib.request.Request(url, headers={
        "Accept": "application/vnd.github+json",
        "User-Agent": "wetype-patch-ci",
        **({"Authorization": f"Bearer {os.environ['GH_TOKEN']}"} if os.environ.get("GH_TOKEN") else {}),
    })
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def is_auto(release: dict) -> bool:
    """判断是不是本流水线自动发布的成品。"""
    if AUTO_MARK in (release.get("body") or ""):
        return True
    return bool(AUTO_TAG.match(release.get("tag_name") or ""))


def main() -> None:
    repo = os.environ.get("MODULE_REPO", "").strip()
    if not repo:
        raise SystemExit("缺少 MODULE_REPO")
    max_mb = float(os.environ.get("MAX_MODULE_MB", "50"))

    releases = get(f"{API}/repos/{repo}/releases?per_page=30")
    if not isinstance(releases, list):
        raise SystemExit(f"读取 Release 列表失败：{releases}")

    auto = [r for r in releases if is_auto(r)]
    manual = [r for r in releases
              if not r.get("draft") and not r.get("prerelease") and not is_auto(r)]
    print(f"Release 列表 {len(releases)} 个，其中流水线自建 {len(auto)} 个已剔除，"
          f"候选模块版本 {len(manual)} 个", file=sys.stderr)
    if auto:
        print(f"  已剔除：{[r['tag_name'] for r in auto]}", file=sys.stderr)

    if not manual:
        raise SystemExit("没有可用的模块 Release（全被识别为流水线自建或草稿）。"
                         "请手动发一个模块 Release。")

    want = os.environ.get("MODULE_ASSET", "").strip()

    # 逐个 release 往下找，直到命中一个带 .apk 的
    for release in manual:
        tag = release.get("tag_name") or release.get("name") or ""
        assets = [a for a in release.get("assets", []) if a["name"].lower().endswith(".apk")]
        if not assets:
            print(f"  跳过 {tag}：没有 .apk 资产", file=sys.stderr)
            continue

        print(f"  命中 {tag}，候选资产 {[a['name'] for a in assets]}", file=sys.stderr)

        if want:
            hit = [a for a in assets if a["name"] == want] or [a for a in assets if want in a["name"]]
            if not hit:
                print(f"  跳过 {tag}：没有名为 {want} 的资产", file=sys.stderr)
                continue
            picked = hit[0]
        else:
            # 同一 release 里可能同时挂模块和已内置整包，取体积最小的那个
            picked = min(assets, key=lambda a: a["size"])

        size_mb = picked["size"] / 1048576
        if size_mb > max_mb:
            raise SystemExit(
                f"挑到的资产 {picked['name']} 有 {size_mb:.1f} MB，超过模块上限 {max_mb} MB。"
                f"\n这多半是挑错了（把已内置的整包当模块）。请用 module_asset 精确指定资产名，"
                f"或检查 Release 里的资产。"
            )

        # tag 形如 WeType_Unique_1.29.0 / v1.29.0，取最后一个版本号片段当模块版本
        found = re.findall(r"\d+(?:\.\d+)+", tag)
        version = found[-1] if found else (tag.lstrip("vV") or "unknown")
        pairs = {
            "tag": tag,
            "version": version,
            "asset": picked["name"],
            "url": picked["browser_download_url"],
            "size": str(picked["size"]),
        }
        for k, v in pairs.items():
            print(f"{k}={v}")

        out = os.environ.get("GITHUB_OUTPUT")
        if out:
            with open(out, "a", encoding="utf-8") as f:
                for k, v in pairs.items():
                    f.write(f"{k}={v}\n")
        return

    raise SystemExit(f"没找到可用的模块 APK（搜了 {len(manual)} 个 Release）。"
                     f"请确认最新模块 Release 里上传了 .apk 资产。")


if __name__ == "__main__":
    sys.exit(main())
